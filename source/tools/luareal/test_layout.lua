-- test_layout.lua: runs main.lua's NATIVE.LAYOUT + NATIVE.layoutCheck under real Lua 5.4 with a stand-in for UE4SS's
-- reflection. MAIN (a global set by the runner) = the path of main.lua.
local f = assert(io.open(MAIN, "rb")) local src = f:read("a") f:close()
src = src:gsub("\r\n", "\n")
local a = assert(src:find("-- GENERATED by source/tools/gen_layout.pl", 1, true), "no table")
local b = assert(src:find("-- (v189, review) ANOTHER BUILD OF THE GAME", 1, true), "no end marker")
NATIVE = {}
assert(load(src:sub(a, b - 1), "layout-part"))()
assert(type(NATIVE.LAYOUT) == "table" and type(NATIVE.layoutCheck) == "function")
local classes, props = 0, 0
for _, c in ipairs(NATIVE.LAYOUT) do classes = classes + 1 for _ in pairs(c[2]) do props = props + 1 end end
print(string.format("table: %d classes, %d properties", classes, props))

-- the stand-in: every class of the table, its properties at the table's offsets plus `shift` for names in `moved`
local function world(opts)
    opts = opts or {}
    StaticFindObject = function(path)
        local short = path:match("%.([^.]+)$")
        if opts.missingClass == short then return nil end
        for _, c in ipairs(NATIVE.LAYOUT) do
            if c[1] == path then
                return {
                    IsValid = function() return true end,
                    ForEachProperty = function(self, cb)
                        if opts.noApi then error("attempt to call a nil value (method 'ForEachProperty')") end
                        for name, off in pairs(c[2]) do
                            if not (opts.gone and opts.gone[name]) then
                                local o = off + ((opts.moved and opts.moved[name]) or 0)
                                cb({ GetFName = function() return { ToString = function() return name end } end, GetOffset_Internal = function() return o end })
                            end
                        end
                        cb({ GetFName = function() return { ToString = function() return "bSomeBool" end } end, GetOffset_Internal = function() return 0x304 end })   -- (a bool the table does not hold)
                    end,
                }
            end
        end
        return nil
    end
end
local function show(tag, r)
    print(string.format("%-28s ok %d / %d, elsewhere %d, not there %d, classes not readable %d | %s", tag, r.ok, r.total, r.bad, r.miss, r.cant, table.concat(r.notes, "; ")))
    return r
end
world()                                             local r1 = show("same layout:", NATIVE.layoutCheck())
world({ moved = { LeftFootSocketLocation = 8 } })    local r2 = show("one property moved:", NATIVE.layoutCheck())
world({ gone = { _catchOrientState = true } })       local r3 = show("one property gone:", NATIVE.layoutCheck())
world({ missingClass = "MenuPage" })                 local r4 = show("a class not there:", NATIVE.layoutCheck())
world({ noApi = true })                              local r5 = show("the API not there:", NATIVE.layoutCheck())
assert(r1.ok == props and r1.total == props and r1.bad == 0 and r1.miss == 0 and r1.cant == 0, "same layout must pass")
assert(r2.bad == 1 and r2.miss == 0 and r2.ok == props - 1, "a moved property must be counted")
assert(r3.miss == 1 and r3.bad == 0, "a missing property must be counted")
assert(r4.cant == 1 and r4.bad == 0 and r4.miss == 0, "a missing class is not a mismatch")
assert(r5.cant == classes and r5.bad == 0 and r5.miss == 0 and r5.total == 0, "no API = nothing counted against the build")
print("ALL ASSERTIONS HELD")
