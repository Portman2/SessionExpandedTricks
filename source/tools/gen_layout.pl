use strict; use warnings;
# gen_layout.pl <exe> <pdb> <symcache> <out.lua.inc>
# Makes the Lua half's layout table (NATIVE.LAYOUT in main.lua): for the game classes whose members the native half
# reads by fixed offset, every reflected property with its offset, taken from the exe the native half was written
# against (PdbDis `prop` reads the Z_Construct_UClass_*_Statics property tables). On another build of the game the
# Lua compares the live offsets (UE4SS reflection) with these before it lets the native half touch anything.
# Bit-field bools are left out (their offset is not in the table: it is computed by a SetBit function).
my ($exe, $pdb, $cache, $outf) = @ARGV; die "usage" unless $outf;
my $dis = "$ENV{USERPROFILE}/.claude/skills/session-mod/scripts/PdbDis.exe"; $dis =~ s/\\/\//g;
my @classes = qw(SessionGame:USkaterAnimInstance SessionGame:ASkaterCharacterBase SessionGame:ASkateboardEx SessionGame:USkateboardExMovementComponent
                 SessionGame:ASessionPlayerController SessionGame:UMenuPage SessionGame:UMenuPageContainer SessionGame:AReplayManager SessionGame:UFlipTrickDefinition
                 Engine:AActor Engine:UActorComponent Engine:USceneComponent Engine:USkinnedMeshComponent Engine:USkeletalMeshComponent
                 Engine:APlayerController Engine:UAudioComponent);   # the engine's own too: the native half reads those by offset as well
open my $e, '<:raw', $exe or die; my $hdr; read($e, $hdr, 0x400); close $e;
my $stamp = unpack('V', substr($hdr, unpack('V', substr($hdr, 0x3c, 4)) + 8, 4));
my ($total, @out) = (0);
push @out, sprintf("-- GENERATED by source/tools/gen_layout.pl from the game exe with PE stamp %08x. Do not edit by hand.", $stamp);
push @out, "NATIVE.LAYOUT = {";
for my $spec (@classes) {
    my ($module, $c) = split /:/, $spec;
    my $txt = `"$dis" "$exe" "$pdb" "$cache" prop Z_Construct_UClass_${c}_Statics 2>&1`;
    my (%p, @order);
    for my $l (split /\r?\n/, $txt) {
        next unless $l =~ /^(\S+)\s+off=0x([0-9a-f]+) dim=(-?\d+) gen=0x([0-9a-f]+) .*\[\?NewProp_(\w+?)\@Z_Construct_UClass_\Q$c\E_Statics\@\@/;
        my ($name, $off, $dim, $gen, $sym) = ($1, hex($2), $3, hex($4), $5);
        next if $name eq '?' || $name ne $sym;            # _SetBit functions, _Inner / _Underlying / _KeyProp ... of containers and enums
        next if $gen == 0x2c;                             # a bool: its 'offset' here is its size
        next if $off < 0x28 || $off > 0x8000 || $dim < 1 || $dim > 64;
        next if exists $p{$name};
        $p{$name} = $off; push @order, $name;
    }
    die "$c: no properties read" unless @order >= 1;
    (my $short = $c) =~ s/^[UA]//;
    my @items = map { sprintf('["%s"] = 0x%x', $_, $p{$_}) } @order;
    push @out, sprintf('    { "/Script/%s.%s", {', $module, $short);
    while (@items) { push @out, '        ' . join(', ', splice(@items, 0, 6)) . ','; }
    push @out, '    } },';
    printf "%-34s %3d properties, offsets 0x%x .. 0x%x\n", $c, scalar(@order), (sort { $a <=> $b } values %p)[0], (sort { $b <=> $a } values %p)[0];
    $total += @order;
}
push @out, "}";
open my $o, '>:raw', $outf or die; print $o join("\r\n", @out), "\r\n"; close $o;
print "\n$total properties of ", scalar(@classes), " classes written to $outf\n";
